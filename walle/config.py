"""Loads config/robot.yaml and merges it over built-in defaults."""

import copy
import os

import yaml

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_CONFIG_PATH = os.path.join(REPO_ROOT, "config", "robot.yaml")
# Written by tools/servo_test.py so the hand-edited robot.yaml keeps its comments.
CALIBRATION_PATH = os.path.join(REPO_ROOT, "config", "servo_calibration.yaml")

DEFAULTS = {
    "drive": {
        "backend": "jetson",       # jetson | mock
        "driver": "l298n",         # l298n | pwm_dir
        "pwm_frequency_hz": 1000,
        "left": {"pwm_pin": 32, "in1_pin": 29, "in2_pin": 31, "inverted": False},
        "right": {"pwm_pin": 33, "in1_pin": 35, "in2_pin": 37, "inverted": False},
        "max_speed": 0.6,          # fraction of full duty, raise once tuned
        "min_duty": 0.25,          # duty at which the motors start to turn
        "turn_gain": 0.7,
        "ramp_per_s": 2.0,         # full scale change takes 0.5 s
    },
    "servos": {
        "backend": "pca9685",      # pca9685 | mock
        "i2c_bus": 8,              # Xavier NX header pins 3/5
        "address": 0x7F,
        "frequency_hz": 50,
        "channels": {},
    },
    "controller": {
        "device": None,            # None = first gamepad found
        "deadzone": 0.12,
        "expo": 0.3,
    },
}


def _merge(base, override):
    for key, value in (override or {}).items():
        if isinstance(value, dict) and isinstance(base.get(key), dict):
            _merge(base[key], value)
        else:
            base[key] = value
    return base


def _read_yaml(path):
    if path and os.path.exists(path):
        with open(path) as fh:
            return yaml.safe_load(fh) or {}
    return {}


def load_config(path=None, calibration_path=None):
    """Return defaults, overlaid with robot.yaml, overlaid with servo calibration."""
    path = path or os.environ.get("WALLE_CONFIG", DEFAULT_CONFIG_PATH)
    calibration_path = calibration_path or CALIBRATION_PATH
    config = copy.deepcopy(DEFAULTS)
    _merge(config, _read_yaml(path))
    _merge(config["servos"]["channels"], _read_yaml(calibration_path).get("channels"))
    return config


def save_calibration(channels, calibration_path=None):
    """Persist per-channel servo limits found with the servo test tool."""
    calibration_path = calibration_path or CALIBRATION_PATH
    with open(calibration_path, "w") as fh:
        fh.write("# Generated by tools/servo_test.py. Overrides servos.channels in robot.yaml.\n")
        yaml.safe_dump({"channels": channels}, fh, default_flow_style=False)
